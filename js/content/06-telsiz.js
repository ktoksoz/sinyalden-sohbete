  <div class="text">
    <h2>RST raporu</h2>
    <p class="lead">Bir görüşmenin ilk alışverişlerinden biri karşı tarafa "sizi nasıl alıyorum" bilgisini vermektir. Bunu üç rakam söyler: okunabilirlik, güç ve ton.</p>
    <ul>
      <li><strong>R (okunabilirlik), 1–5:</strong> 1 okunamıyor, 3 güçlükle okunuyor, 5 kusursuz okunuyor.</li>
      <li><strong>S (güç), 1–9:</strong> sinyalin gücü; 1 çok zayıf, 9 çok güçlü. Alıcının S-metresi kabaca her S biriminde 6 dB artar.</li>
      <li><strong>T (ton), 1–9:</strong> yalnız CW'de verilir. 9 saf, temiz bir ton; düşük rakamlar uğultulu, cıvıltılı ya da hırıltılı bir tonu anlatır.</li>
    </ul>
    <p>Okunabilirlik yalnızca güce bağlı değildir: güçlü bir sinyal güçlü bir parazitin içinde okunamayabilir, zayıf bir sinyal sessiz bir bantta tertemiz okunabilir. Tam tersi de mümkündür.</p>
    <details class="more"><summary>Daha fazla: herkes neden 599 veriyor?</summary>
      <p>Yarışmalarda ve kısa görüşmelerde rapor çoğu zaman alışkanlıkla 599 (5NN) verilir. Gerçek bir rapor vermek, özellikle zayıf sinyallerde, karşı taraf için daha değerlidir.</p>
    </details>
    <p class="try">Kaydırıcılarla bir sinyal kurun ve dinleyin; deney hangi raporu vereceğinizi hesaplar. Sonra "Rapor ver" ile rastgele bir sinyali dinleyip RST'yi siz tahmin edin.</p>
  </div>
