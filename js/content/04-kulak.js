    <p class="lead">Mors bir dil gibi kulakla öğrenilir. Bir harfi "nokta, nokta, çizgi, nokta" diye saymak yerine, onun tek parça ritmini tanımak gerekir: <span class="kod">di-di-dah-dit</span> bir F'dir, tıpkı bir kelimenin sesi gibi.</p>
